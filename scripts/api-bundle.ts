import { build, type Plugin } from "esbuild";
import { fileURLToPath } from "node:url";

/**
 * Bundles the Vercel Function (server/vercel-entry.ts) into one ES module.
 *
 * Why: this project is an ES-module package whose TypeScript uses extensionless
 * relative imports (`from "./database"`). Node cannot load those at runtime, and
 * Vercel's per-file TypeScript compile does not rewrite them, so the function
 * would crash with "module not found". Bundling resolves every first-party import
 * at build time. Third-party packages stay external: Vercel installs them from
 * package.json and traces them into the function.
 *
 * PGlite (the local/test database) is replaced by a stub: the function always
 * uses the hosted Postgres, and PGlite's WebAssembly would only slow cold starts.
 */
const root = new URL("../", import.meta.url);
const path = (relative: string) => fileURLToPath(new URL(relative, root));

const stubPglite: Plugin = {
  name: "stub-pglite",
  setup(b) {
    b.onResolve({ filter: /(^|\/)pglite$/ }, () => ({
      path: "pglite-stub",
      namespace: "stub",
    }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({
      contents:
        'export const pgliteDriver = async () => { throw new Error("The local PGlite database is not part of the serverless bundle."); };',
      loader: "js",
    }));
  },
};

export const apiBundlePath = path("api/index.mjs");

export async function bundleApi({ write = true } = {}) {
  const result = await build({
    entryPoints: [path("server/vercel-entry.ts")],
    outfile: apiBundlePath,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    packages: "external",
    plugins: [stubPglite],
    banner: {
      js: "// GENERATED by `npm run build:api` from server/vercel-entry.ts. Do not edit.\n",
    },
    legalComments: "none",
    logLevel: "silent",
    write,
  });
  return result.outputFiles?.[0]?.text;
}
